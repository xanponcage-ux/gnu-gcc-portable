  BEGIN
    SELECT payload INTO l_payload FROM ldp_dash_cache_v30
    WHERE filter_key = l_key AND built_at > SYSTIMESTAMP - INTERVAL '15' MINUTE;
    COMMIT;
    RETURN l_payload;
  EXCEPTION WHEN NO_DATA_FOUND THEN NULL;
  END;


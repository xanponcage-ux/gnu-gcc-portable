  -- Fixed-length component digests preserve parameter boundaries.
  SELECT STANDARD_HASH(
    RAWTOHEX(STANDARD_HASH(NVL(p_mill, N'(All)'), 'SHA256')) ||
    RAWTOHEX(STANDARD_HASH(NVL(p_order_type, N'(All)'), 'SHA256')) ||
    RAWTOHEX(STANDARD_HASH(NVL(p_vertical, N'(All)'), 'SHA256')) ||
    RAWTOHEX(STANDARD_HASH(NVL(p_customer, N'(All)'), 'SHA256')) ||
    RAWTOHEX(STANDARD_HASH(NVL(p_region, N'(All)'), 'SHA256')) ||
    RAWTOHEX(STANDARD_HASH(NVL(p_freight, N'(All)'), 'SHA256')) ||
    RAWTOHEX(STANDARD_HASH(NVL(p_block, N'(All)'), 'SHA256')),

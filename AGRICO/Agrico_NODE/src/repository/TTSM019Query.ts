export const getFGMATDataDetailed = async (
  plant: any,
  matno: any,
  frmDt: any,
  toDt: any
) => {
  try {
    var sql = `SELECT 
    ENC_NO_MATNR,
    (
        SELECT
            maktx
        FROM
            v_makt
        WHERE
            mandt = '600'
            AND matnr = ENC_NO_MATNR
    ) AS MAT_DESC,
    ENC_PRINT_SPEC,
    ENC_ODIA,
    ENC_SEC2_MIN MIN_WIDTH,
    ENC_SEC2_MAX MAX_WIDTH,
    ENC_SEC1_MIN  MIN_THICK,
    ENC_SEC1_MAX  MAX_THICK,
    ENC_SEC3_MIN  MIN_LEN,
    ENC_SEC3_MAX  MAX_LEN,
    SUM(ENC_ORD_QUANTITY) AS ORD_QTY,
    SUM(F_DISPATCH(ENC_CD_EPA, ENC_ID_ORDER, ENC_NO_ITEM)) AS SUM_DISPATCH,
    (select SUM(F_DISPATCH(ENC_CD_EPA, ENC_ID_ORDER, ENC_NO_ITEM)) from V_END_CUST_ORD_EPA
    WHERE ENC_CD_EPA = :plant
    AND ENC_NO_MATNR=A.ENC_NO_MATNR
    --AND ENC_ST_ORDER = 'A'
    AND ENC_SLIT_PLAN='TUBE'
    AND to_date(to_char(ENC_DT_ORD_CREATE, 'dd-Mon-yyyy'), 'dd-Mon-yyyy') >= TRUNC(ADD_MONTHS(TO_DATE(NVL(:toDt,to_char(sysdate,'dd-Mon-yyyy')),'dd-Mon-yyyy'), -6), 'MM') 
    AND to_date(to_char(ENC_DT_ORD_CREATE, 'dd-Mon-yyyy'), 'dd-Mon-yyyy') < TRUNC(TO_DATE(NVL(:toDt,to_char(sysdate,'dd-Mon-yyyy')),'dd-Mon-yyyy'), 'MM')
    GROUP BY ENC_NO_MATNR) AS LAST_SIX_MONTHS_DISPATCH,
   (SELECT COUNT(DISTINCT TO_CHAR(EOM_DT_INVOICE, 'MM')) 
    FROM V_EPA_PRODN
    WHERE EOM_NO_MATNR = A.ENC_NO_MATNR
      AND EOM_CD_EPA = '0788'
      AND EOM_CD_STATUS IN ('WL', 'WC')
      AND EOM_DT_INVOICE >= TRUNC(ADD_MONTHS(TO_DATE(NVL(:toDt,to_char(sysdate,'dd-Mon-yyyy')),'dd-Mon-yyyy'), -6), 'MM')
      AND TO_CHAR(EOM_DT_INVOICE, 'MM') <> TO_CHAR(TO_DATE(NVL(:toDt,to_char(sysdate,'dd-Mon-yyyy')),'dd-Mon-yyyy'), 'MM') ) AS DISTINCT_MONTH_COUNT,  
    SUM(F_WIP(ENC_CD_EPA,ENC_ID_ORDER,ENC_NO_ITEM)) AS WIP_QTY,
    SUM(F_FG_STOCK(ENC_CD_EPA,ENC_ID_ORDER,ENC_NO_ITEM)) AS FG_STOCK,
    SUM(ENC_ORD_QUANTITY-F_DISPATCH(ENC_CD_EPA, ENC_ID_ORDER, ENC_NO_ITEM)) AS BTD,
    (SELECT TMM_SFG_MAT FROM V_TUB_MATL_MAPPING WHERE TMM_FG_MAT=ENC_NO_MATNR AND ROWNUM=1) SFG_MAT,
    (
      SELECT
          maktx
      FROM
          v_makt
      WHERE
          mandt = '600'
          AND matnr = (SELECT TMM_SFG_MAT FROM V_TUB_MATL_MAPPING WHERE TMM_FG_MAT=ENC_NO_MATNR AND ROWNUM=1)
   ) AS SFG_MAT_DESC
FROM 
    V_END_CUST_ORD_EPA A
WHERE 
    ENC_CD_EPA = :plant
    AND ENC_ST_ORDER = 'A'
    AND ENC_SLIT_PLAN='TUBE'
    AND ENC_PRINT_SPEC IS NOT NULL
    `;
    let binds = {
      plant: plant,
      toDt: toDt,
    };
    if (matno && Array.isArray(matno) && matno.length > 1) {
      if (matno && Array.isArray(matno) && matno.length > 1) {
        sql += `AND ENC_PRINT_SPEC in(` + matno.join(",") + `) `;
        // binds["matnoFrm"] = matnoFrm.join(',');
      }
    } else {
      if (matno && matno !== "") {
        sql += `AND ENC_PRINT_SPEC = nvl(:matno, ENC_PRINT_SPEC) `;
        binds["matno"] = Array.isArray(matno) ? matno[0] : matno;
      }
    }
    if (frmDt && toDt && frmDt != "" && toDt != "") {
      sql += ` AND to_date(to_char(ENC_DT_ORD_CREATE,'dd-Mon-yyyy'),'dd-Mon-yyyy') >= TO_DATE(NVL(:frmDt,to_char(ENC_DT_ORD_CREATE,'dd-Mon-yyyy')),'dd-Mon-yyyy')
          AND to_date(to_char(ENC_DT_ORD_CREATE,'dd-Mon-yyyy'),'dd-Mon-yyyy') <= TO_DATE(NVL(:toDt,to_char(ENC_DT_ORD_CREATE,'dd-Mon-yyyy')),'dd-Mon-yyyy')`;
      binds["frmDt"] = frmDt;
    }
    // sql += ` ORDER BY TBD_CD_EPA,TBD_CD_PROC , TBD_ID_BATCH,TBD_RSN_CD `;
    sql += `GROUP BY 
    ENC_NO_MATNR,
    ENC_PRINT_SPEC,
    ENC_ODIA,
    ENC_SEC2_MIN,
    ENC_SEC2_MAX,
    ENC_SEC1_MIN,
    ENC_SEC1_MAX,
    ENC_SEC3_MIN,
    ENC_SEC3_MAX`;
    console.log(sql, binds);
    return await query.executeQuery(sql, binds);
  } catch (error) {
    console.log(error);
    throw new Error.InternalServerError("Error!");
  }
};
